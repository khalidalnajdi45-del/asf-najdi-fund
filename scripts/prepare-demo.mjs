// Prepares the self-contained DEMO build: Postgres (PGlite/WASM) runs inside the browser,
// loaded with the real migrations + demo seed. Used only when NEXT_PUBLIC_DEMO=1.
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const src = join(root, 'node_modules/@electric-sql/pglite/dist');
const dst = join(root, 'public/pglite');
const DEMO = process.env.NEXT_PUBLIC_DEMO === '1';
if (DEMO) {
rmSync(dst, { recursive: true, force: true });
mkdirSync(join(dst, 'contrib'), { recursive: true });
for (const f of readdirSync(src)) {
  if (/\.(js|wasm|data)$/.test(f) || f === 'pgcrypto.tar.gz') cpSync(join(src, f), join(dst, f));
}
for (const f of readdirSync(join(src, 'contrib'))) if (/^pgcrypto\.js$/.test(f)) cpSync(join(src, 'contrib', f), join(dst, 'contrib', f));
for (const d of ['fs', 'templating', 'live', 'vector', 'worker']) {
  try { cpSync(join(src, d), join(dst, d), { recursive: true, filter: p => !/\.(map|ts|cts|cjs)$/.test(p) }); } catch {}
}
}

const mig = readdirSync(join(root, 'supabase/migrations')).filter(f => /^\d{4}_.*\.sql$/.test(f) && !/_platform/.test(f)).sort();
const parts = [readFileSync(join(root, 'tests/supabase_stub.sql'), 'utf8'), ...mig.map(f => readFileSync(join(root, 'supabase/migrations', f), 'utf8'))];
writeFileSync(join(root, 'src/lib/demo/sql.generated.ts'),
  `// generated by scripts/prepare-demo.mjs — do not edit\nexport const SCHEMA_SQL = ${JSON.stringify(parts.join('\n;\n'))};\nexport const SEED_SQL = ${JSON.stringify(readFileSync(join(root, 'supabase/seed.sql'), 'utf8'))};\n`);
console.log('demo prepared:', mig.length, 'migrations');
