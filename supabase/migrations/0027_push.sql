-- 0027 Push notifications (iPhone / Android / desktop Web Push).
-- Every in-app notification can also be pushed to the user's devices. Users choose categories.
-- The actual sending happens in the `send-push` Edge Function; on Supabase, 0028_platform_push replaces
-- _push_dispatch() with a pg_net call. Here (tests / demo) it's a no-op.

create table public.push_subscriptions (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references public.app_users(id) on delete cascade,
  endpoint   text not null unique check (endpoint ~ '^https://'),
  p256dh     text not null,
  auth       text not null,
  user_agent text,
  created_at timestamptz not null default now(),
  last_ok_at timestamptz
);
create index on public.push_subscriptions(user_id);

create table public.push_prefs (
  user_id uuid primary key references public.app_users(id) on delete cascade,
  prefs   jsonb not null default '{}'::jsonb
);

-- VAPID key pair (generated by the Edge Function on first use; only service_role can read it)
create table public.push_vapid (
  id          int primary key default 1 check (id = 1),
  public_key  text not null,
  private_key text not null,
  created_at  timestamptz not null default now()
);

alter table public.push_subscriptions enable row level security;
alter table public.push_prefs enable row level security;
alter table public.push_vapid enable row level security;
revoke all on public.push_subscriptions, public.push_prefs, public.push_vapid from public, anon, authenticated;

-- ------------------------------------------------------------ categories
/** Which preference category a notification type belongs to. */
create or replace function public.push_category(p_type text) returns text
language sql immutable as $$
  select case
    when p_type in ('contribution_reminder','contribution_overdue','repayment_reminder','repayment_overdue','due_today') then 'dues'
    when p_type in ('loan_approved','loan_rejected','loan_cancelled','loan_disbursed','loan_repaid',
                    'withdrawal_approved','withdrawal_paid','withdrawal_rejected','deposit_rejected') then 'requests'
    when p_type in ('contribution_recorded','repayment_recorded','deposit_received','transaction_reversed') then 'payments'
    when p_type in ('event_invite','event_cancelled') then 'events'
    when p_type in ('task_reminder') then 'tasks'
    when p_type in ('loan_request','loan_received','loan_auto_approved','deposit_request','withdrawal_request',
                    'investment_maturity','daily_summary') then 'admin'
    else 'fund' end   -- announcement, message, profit_distribution, monthly_report, welcome …
$$;

create or replace function public._push_wanted(p_user uuid, p_type text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.push_subscriptions where user_id = p_user)
     and coalesce((select (prefs ->> public.push_category(p_type))::boolean from public.push_prefs where user_id = p_user), true)
$$;

/** Hand a notification to the push sender. Replaced on Supabase by 0028_platform_push. */
create or replace function public._push_dispatch(p_notification uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  return;
end $$;

create or replace function public._notifications_push() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if public._push_wanted(new.user_id, new.type) then
    perform public._push_dispatch(new.id);
  end if;
  return new;
end $$;
create trigger notifications_push after insert on public.notifications
  for each row execute function public._notifications_push();

-- ------------------------------------------------------------ user RPCs
create or replace function public.save_push_subscription(p_endpoint text, p_p256dh text, p_auth text, p_ua text default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'غير مصرح'; end if;
  if (select count(*) from public.push_subscriptions where user_id = auth.uid()) >= 10 then
    delete from public.push_subscriptions where id = (select id from public.push_subscriptions where user_id = auth.uid() order by created_at limit 1);
  end if;
  insert into public.push_subscriptions(user_id, endpoint, p256dh, auth, user_agent)
  values (auth.uid(), p_endpoint, p_p256dh, p_auth, left(p_ua, 300))
  on conflict (endpoint) do update set user_id = excluded.user_id, p256dh = excluded.p256dh, auth = excluded.auth,
                                       user_agent = excluded.user_agent, created_at = now();
end $$;

create or replace function public.delete_push_subscription(p_endpoint text) returns void
language sql security definer set search_path = public as $$
  delete from public.push_subscriptions where endpoint = p_endpoint and user_id = auth.uid()
$$;

create or replace function public.my_push_settings() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'devices', (select count(*) from public.push_subscriptions where user_id = auth.uid()),
    'prefs', coalesce((select prefs from public.push_prefs where user_id = auth.uid()), '{}'::jsonb))
$$;

create or replace function public.set_push_pref(p_category text, p_on boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'غير مصرح'; end if;
  if p_category not in ('dues','requests','payments','events','tasks','fund','admin') then raise exception 'تصنيف غير صالح'; end if;
  insert into public.push_prefs(user_id, prefs) values (auth.uid(), jsonb_build_object(p_category, p_on))
  on conflict (user_id) do update set prefs = public.push_prefs.prefs || jsonb_build_object(p_category, p_on);
end $$;

revoke execute on function public._push_wanted(uuid,text), public._push_dispatch(uuid), public._notifications_push() from public, anon, authenticated;
revoke execute on function public.save_push_subscription(text,text,text,text), public.delete_push_subscription(text),
  public.my_push_settings(), public.set_push_pref(text,boolean) from public, anon;
grant execute on function public.save_push_subscription(text,text,text,text), public.delete_push_subscription(text),
  public.my_push_settings(), public.set_push_pref(text,boolean) to authenticated;

-- ------------------------------------------------------------ more things worth a buzz
/** Calendar tasks: a reminder 15 minutes ahead (timed tasks), or at the morning run (untimed tasks). Runs every 15 min. */
create or replace function public.run_task_reminders() returns int
language plpgsql security definer set search_path = public as $$
declare n int := 0; r record;
  v_now timestamp := (now() at time zone 'Asia/Riyadh');
begin
  if auth.uid() is not null then perform public.assert_manager(); end if;
  for r in select * from public.member_tasks
            where not done and task_time is not null
              and (task_date + task_time::time) > v_now - interval '5 minutes'
              and (task_date + task_time::time) <= v_now + interval '20 minutes' loop
    perform public._notify(r.user_id, 'task_reminder', 'تذكير: ' || r.title,
      'الساعة ' || r.task_time || coalesce(' — ' || r.note, ''), null, 'task-' || r.id);
    n := n + 1;
  end loop;
  return n;
end $$;
revoke execute on function public.run_task_reminders() from public, anon;

/** Morning run: due-today nudges, untimed tasks of the day, and the manager's summary. */
create or replace function public.run_morning_push() returns int
language plpgsql security definer set search_path = public as $$
declare d date := public.fund_today(); n int := 0; r record; v_over int; v_over_amt numeric; v_req int; v_body text;
begin
  if auth.uid() is not null then perform public.assert_manager(); end if;
  -- payments due today
  for r in select member_id, sum(amount_outstanding) amt from public.v_contribution_status
            where status not in ('paid','waived') and due_date = d group by 1 loop
    perform public._notify_member(r.member_id, 'due_today', 'اشتراك الصندوق مستحق اليوم',
      'المبلغ المستحق ' || to_char(r.amt, 'FM999,999,990.00') || ' ريال.', '/member/contributions', 'due-c-' || r.member_id || '-' || d);
    n := n + 1;
  end loop;
  for r in select l.member_id, sum(i.amount_remaining) amt from public.v_installment_status i join public.loans l on l.id = i.loan_id
            where i.status <> 'paid' and l.status in ('disbursed','active','overdue') and i.due_date = d group by 1 loop
    perform public._notify_member(r.member_id, 'due_today', 'قسط القرض مستحق اليوم',
      'المبلغ المستحق ' || to_char(r.amt, 'FM999,999,990.00') || ' ريال.', '/member/loans', 'due-i-' || r.member_id || '-' || d);
    n := n + 1;
  end loop;
  -- untimed tasks for today
  for r in select user_id, count(*) c, min(title) t from public.member_tasks where not done and task_date = d and task_time is null group by 1 loop
    perform public._notify(r.user_id, 'task_reminder', 'مهامك اليوم',
      case when r.c = 1 then r.t else r.t || ' و' || (r.c - 1) || ' مهام أخرى' end, '/member', 'tasks-' || r.user_id || '-' || d);
    n := n + 1;
  end loop;
  -- manager summary (only when there's something to act on)
  select count(*), coalesce(sum(amount_outstanding),0) into v_over, v_over_amt from public.v_contribution_status where status = 'overdue';
  select v_over + count(*), v_over_amt + coalesce(sum(amount_remaining),0) into v_over, v_over_amt from public.v_installment_status where status = 'overdue';
  select (select count(*) from public.loans where status = 'pending')
       + (select count(*) from public.member_deposits where status = 'requested')
       + (select count(*) from public.deposit_withdrawals where status = 'pending') into v_req;
  if v_over > 0 or v_req > 0 then
    v_body := concat_ws(' · ',
      case when v_req > 0 then v_req || ' طلب بانتظار قرارك' end,
      case when v_over > 0 then v_over || ' مستحق متأخر (' || to_char(v_over_amt, 'FM999,999,990') || ' ريال)' end);
    perform public._notify(u.id, 'daily_summary', 'ملخص الصباح', v_body, '/admin', 'summary-' || d)
      from public.app_users u where u.role = 'manager' and u.is_active;
  end if;
  return n;
end $$;
revoke execute on function public.run_morning_push() from public, anon;
